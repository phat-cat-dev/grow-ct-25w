'use strict';

// Tests for render-map-md.js. Node's built-in test runner, no dependencies.
// Run with: node --test tools/pathways/core/tools/test/

const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { execFileSync } = require('node:child_process');

const TOOL = path.join(__dirname, '..', 'render-map-md.js');
const FIXTURES = path.join(__dirname, 'fixtures');
const { renderMarkdown, outputPathFor } = require(TOOL);

function loadGoodMap() {
  return JSON.parse(fs.readFileSync(path.join(FIXTURES, 'good-map.json'), 'utf8'));
}

test('first line states the file is generated and must not be hand-edited', () => {
  const md = renderMarkdown(loadGoodMap(), 'good-map.json');
  const firstLine = md.split('\n')[0];
  assert.match(firstLine, /[Gg]enerated/);
  assert.match(firstLine, /not.*hand-edit|never.*hand-edit/i);
});

test('renders one section per catalogue pathway, in catalogue order', () => {
  const catalogue = require(path.join(__dirname, '..', '..', '..', '..', '..', 'catalogue', 'pathways.json'));
  const md = renderMarkdown(loadGoodMap(), 'good-map.json');
  let lastIndex = -1;
  for (const pathway of catalogue.pathways) {
    const heading = `## adapt-${pathway.id}`;
    const idx = md.indexOf(heading);
    assert.ok(idx !== -1, `expected heading "${heading}" in rendered markdown`);
    assert.ok(idx > lastIndex, `expected "${heading}" to appear after the previous pathway's heading`);
    lastIndex = idx;
  }
});

test('a pathway with no statements is listed as having none', () => {
  const md = renderMarkdown(loadGoodMap(), 'good-map.json');
  const idx = md.indexOf('## adapt-academic-writing');
  const section = md.slice(idx, md.indexOf('## adapt-presenting'));
  assert.match(section, /No statements for this pathway\./);
});

test('a pathway with statements renders its chunk id, strength, block type, orientation, extract, agent instruction and status', () => {
  const md = renderMarkdown(loadGoodMap(), 'good-map.json');
  const idx = md.indexOf('## adapt-referencing');
  const section = md.slice(idx, md.indexOf('## adapt-criticality'));
  assert.match(section, /qaa\/fixture-subject-2026\/1\.1/);
  assert.match(section, /direct/);
  assert.match(section, /subject_knowledge/);
  assert.match(section, /academic/);
  assert.match(section, /reference sources accurately and to maintain academic integrity/);
  assert.match(section, /Fixture only: not a real grounding statement\./);
  assert.match(section, /proposed/);
});

test('whole-map agent instructions render once, before any pathway section', () => {
  const md = renderMarkdown(loadGoodMap(), 'good-map.json');
  const instrIdx = md.indexOf('Fixture map for validate-map.js and render-map-md.js tests.');
  const firstPathwayIdx = md.indexOf('## adapt-');
  assert.ok(instrIdx !== -1);
  assert.ok(instrIdx < firstPathwayIdx);
});

test('excluded chunks are listed with their reason', () => {
  const md = renderMarkdown(loadGoodMap(), 'good-map.json');
  assert.match(md, /qaa\/fixture-subject-2026\/front-matter-1/);
  assert.match(md, /front matter: material before the first numbered section/);
});

test('outputPathFor replaces a trailing .json with .md', () => {
  assert.equal(outputPathFor('/a/b/foo.adapt-map.json'), '/a/b/foo.adapt-map.md');
});

test('CLI invocation writes the .md file beside a copy of the map', () => {
  const tmpDir = fs.mkdtempSync(path.join(os.tmpdir(), 'render-map-md-test-'));
  const tmpMap = path.join(tmpDir, 'good-map.json');
  fs.copyFileSync(path.join(FIXTURES, 'good-map.json'), tmpMap);
  const out = execFileSync('node', [TOOL, tmpMap], { encoding: 'utf8' });
  assert.match(out, /^Wrote /);
  const mdPath = path.join(tmpDir, 'good-map.md');
  assert.ok(fs.existsSync(mdPath));
  const content = fs.readFileSync(mdPath, 'utf8');
  assert.match(content, /^<!-- Generated by render-map-md\.js/);
  fs.rmSync(tmpDir, { recursive: true, force: true });
});
