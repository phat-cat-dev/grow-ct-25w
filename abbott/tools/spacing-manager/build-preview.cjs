const fs = require('node:fs');
const path = require('node:path');

const root = path.resolve(__dirname, '..', '..');
const modules = new Map();
const moduleId = filename => path.relative(root, filename).split(path.sep).join('/');
function collect(filename) {
  const id = moduleId(filename);
  if (modules.has(id)) return id;
  modules.set(id, '');
  let source = fs.readFileSync(filename, 'utf8');
  const exports = new Set();
  source = source.replace(/import \{([^}]+)\} from '([^']+)';/g, (_, names, dependency) => {
    const dependencyId = collect(path.resolve(path.dirname(filename), dependency));
    return `const {${names}} = load(${JSON.stringify(dependencyId)});`;
  });
  source = source.replace(/export \{([^}]+)\};/g, (_, names) => {
    names.split(',').map(name => name.trim()).forEach(name => exports.add(name));
    return '';
  });
  source = source.replace(/export (function|const|let) (\w+)/g, (_, kind, name) => {
    exports.add(name);
    return `${kind} ${name}`;
  }).replaceAll('import.meta.url', 'moduleUrl');
  modules.set(id, `function(load, moduleUrl) {\n${source}\nreturn { ${[...exports].join(', ')} };\n}`);
  return id;
}
const entry = collect(path.join(__dirname, 'auto-mount.js'));
const output = `// Generated by node tools\\spacing-manager\\build-preview.cjs. Do not edit directly.
(() => {
  const base = new URL('../../', document.currentScript.src);
  const modules = {
${[...modules].map(([id, source]) => `${JSON.stringify(id)}: ${source}`).join(',\n')}
  };
  const cache = new Map();
  function load(id) {
    if (!cache.has(id)) cache.set(id, modules[id](load, new URL(id, base).href));
    return cache.get(id);
  }
  load(${JSON.stringify(entry)});
})();
`;
fs.writeFileSync(path.join(__dirname, 'spacing-manager.bundle.js'), output);
console.log(`Built spacing-manager.bundle.js from ${modules.size} local modules.`);
