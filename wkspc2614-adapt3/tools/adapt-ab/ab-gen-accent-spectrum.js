#!/usr/bin/env node
'use strict';
/**
 * ab-gen-accent-spectrum.js
 *
 * Generate the 12-family accent spectrum as portable CSS tokens for the
 * adapt-ab-theme module, from design-kb/section-schemas/accent-spectrum.json
 * and the formula in docs/authoring/theme-formula-map.md §2.8 (A-v2, ruled
 * 12 Oct 2026) + §2.5 (companions).
 *
 * Emits two files under adapt-ab-theme/layers/:
 *   L4-accent-spectrum.css  — --ab-base-pf-default-[<formula>-]accent-<family>-<dir>-<NN>
 *                             + companion colours + the reactive helper seeds
 *   L3-accent-spectrum.css  — --ab-base-[<formula>-]accent-<family>-<dir>-<NN> = var(L5, L4)
 *
 * NAMING (decisions, stated so they are catchable):
 *   • mono (the default set) carries NO formula marker at L4/L3 — it is the bare
 *     `accent-<family>-<dir>-<NN>` the schema note shows for the L4 default.
 *   • the 7 colour-theory sets carry `<formula>-` at L4/L3 (the discriminator).
 *   • the authoring-only markers (-pf-/-tmp-/-<n>-/-<theme>-) do NOT appear here;
 *     they "earn their place only in the authoring layers" (L5/L6) per §2.8.
 *
 * DERIVATION (runtime-reactive, so one anchor choice re-derives everything):
 *   accent-s      = var(--ab-base-pf-default-accent-s)  (= user-s, the shared chroma)
 *   shade-offset  = (100 - user-l-num) - round((100 - user-l-num), 10)   via CSS round()
 *   base(F,formula) = hsl( (Hf + angle[formula]) mod 360  accent-s  50% )
 *   dark-<NN>     = color-mix(in srgb, base, black calc((NN + shade-offset) * 1%))
 *   light-<NN>    = color-mix(in srgb, base, white calc((NN + shade-offset) * 1%))
 * Family hues and band labels are fixed constants; only chroma + offset react.
 * No per-family anchor PIN is emitted (the pin is an optional named override,
 * §2.8 "in the character of the choice, not necessarily identical"; it depends
 * on hue→family, which is not computable in pure CSS, so it belongs in a pack).
 *
 * Usage: node tools/adapt-ab/ab-gen-accent-spectrum.js
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..', '..');
const SCHEMA = path.join(ROOT, 'design-kb', 'section-schemas', 'accent-spectrum.json');
const OUT_DIR = path.join(ROOT, 'adapt-ab-theme', 'layers');

const schema = JSON.parse(fs.readFileSync(SCHEMA, 'utf8'));
const families = schema.families;          // [{name,hue}]
const bandsDark = schema.bands.dark;       // [10..90]
const bandsLight = schema.bands.light;

// mono + the 7 colour-theory rotations (§2.5 angles). mono has no marker + angle 0.
const FORMULAS = [
  { name: 'mono',           marker: '',               angle: 0 },
  { name: 'complementary',  marker: 'complementary-', angle: 180 },
  { name: 'split-a',        marker: 'split-a-',       angle: 150 },
  { name: 'split-b',        marker: 'split-b-',       angle: 210 },
  { name: 'triad-a',        marker: 'triad-a-',       angle: 120 },
  { name: 'triad-b',        marker: 'triad-b-',       angle: 240 },
  { name: 'analogous-lo',   marker: 'analogous-lo-',  angle: -30 },
  { name: 'analogous-hi',   marker: 'analogous-hi-',  angle: 30 },
];

const COMPANIONS = [   // §2.5 companions — single colours off primary-h
  { name: 'complementary', angle: 180 },
  { name: 'split-a',       angle: 150 },
  { name: 'split-b',       angle: 210 },
  { name: 'triad-a',       angle: 120 },
  { name: 'triad-b',       angle: 240 },
  { name: 'analogous-lo',  angle: -30 },
  { name: 'analogous-hi',  angle: 30 },
];

const ACCENT_S = 'var(--ab-base-pf-default-accent-s)';
const OFFSET = 'var(--ab-base-pf-default-shade-offset)';
const mod360 = h => ((h % 360) + 360) % 360;

function baseHsl(hue) { return `hsl(${hue} ${ACCENT_S} 50%)`; }
function mix(hue, mixColor, band) {
  return `color-mix(in srgb, ${baseHsl(hue)}, ${mixColor} calc((${band} + ${OFFSET}) * 1%))`;
}

// ---- L4 ----
const l4 = [];
l4.push(`/* ===========================================================================`);
l4.push(` * adapt-ab-theme — LAYER 4: accent spectrum defaults`);
l4.push(` *   --ab-base-pf-default-[<formula>-]accent-<family>-<dark|light>-<NN>`);
l4.push(` * Generated by tools/adapt-ab/ab-gen-accent-spectrum.js from`);
l4.push(` * design-kb/section-schemas/accent-spectrum.json (formula: theme-formula-map §2.8/§2.5).`);
l4.push(` * Runtime-reactive: chroma = accent-s (= user-s); shade-offset computed from the`);
l4.push(` * anchor lightness via CSS round(), so a pack changing the anchor re-derives all.`);
l4.push(` * mono = no formula marker; the 7 rotation sets carry <formula>-. Do not hand-edit.`);
l4.push(` * =========================================================================== */`);
l4.push(`:root {`);
l4.push(`  /* reactive helper seeds (themeable via L5) */`);
l4.push(`  --ab-base-pf-default-accent-s: var(--ab-theme-pf-default-accent-s, var(--ab-base-pf-default-user-s));`);
l4.push(`  --ab-base-pf-default-user-l-num: var(--ab-theme-pf-default-user-l-num, 14);`);
l4.push(`  --ab-base-pf-default-shade-offset: calc((100 - var(--ab-base-pf-default-user-l-num)) - round((100 - var(--ab-base-pf-default-user-l-num)), 10));`);
l4.push(`  /* companion single colours (§2.5): primary-h rotated at companion-s/-l */`);
l4.push(`  --ab-base-pf-default-companion-s: var(--ab-theme-pf-default-companion-s, 55%);`);
l4.push(`  --ab-base-pf-default-companion-l: var(--ab-theme-pf-default-companion-l, 45%);`);
for (const c of COMPANIONS) {
  const sign = c.angle < 0 ? `- ${-c.angle}` : `+ ${c.angle}`;
  l4.push(`  --ab-base-pf-default-companion-${c.name}: hsl(calc(var(--ab-base-pf-default-user-h) ${sign}) var(--ab-base-pf-default-companion-s) var(--ab-base-pf-default-companion-l));`);
}
let n4 = 0;
for (const f of FORMULAS) {
  l4.push('');
  l4.push(`  /* ${f.name}${f.angle ? ` (hue ${f.angle >= 0 ? '+' : ''}${f.angle})` : ''} */`);
  for (const fam of families) {
    const hue = mod360(fam.hue + f.angle);
    for (const b of bandsDark)  { l4.push(`  --ab-base-pf-default-${f.marker}accent-${fam.name}-dark-${b}: ${mix(hue, 'black', b)};`); n4++; }
    for (const b of bandsLight) { l4.push(`  --ab-base-pf-default-${f.marker}accent-${fam.name}-light-${b}: ${mix(hue, 'white', b)};`); n4++; }
  }
}
l4.push(`}`);
l4.push('');

// ---- L3 ----
const l3 = [];
l3.push(`/* ===========================================================================`);
l3.push(` * adapt-ab-theme — LAYER 3: accent spectrum pivots`);
l3.push(` *   --ab-base-[<formula>-]accent-<family>-<dark|light>-<NN> = var(L5-template, L4-default)`);
l3.push(` * Generated by tools/adapt-ab/ab-gen-accent-spectrum.js. Do not hand-edit.`);
l3.push(` * =========================================================================== */`);
l3.push(`:root {`);
l3.push(`  --ab-base-companion-s: var(--ab-theme-pf-default-companion-s, var(--ab-base-pf-default-companion-s));`);
for (const c of COMPANIONS) {
  l3.push(`  --ab-base-companion-${c.name}: var(--ab-theme-pf-default-companion-${c.name}, var(--ab-base-pf-default-companion-${c.name}));`);
}
let n3 = 0;
for (const f of FORMULAS) {
  l3.push('');
  l3.push(`  /* ${f.name} */`);
  for (const fam of families) {
    for (const dir of ['dark', 'light']) {
      const bands = dir === 'dark' ? bandsDark : bandsLight;
      for (const b of bands) {
        const tail = `${f.marker}accent-${fam.name}-${dir}-${b}`;
        l3.push(`  --ab-base-${tail}: var(--ab-theme-pf-default-${tail}, var(--ab-base-pf-default-${tail}));`);
        n3++;
      }
    }
  }
}
l3.push(`}`);
l3.push('');

fs.writeFileSync(path.join(OUT_DIR, 'L4-accent-spectrum.css'), l4.join('\n'));
fs.writeFileSync(path.join(OUT_DIR, 'L3-accent-spectrum.css'), l3.join('\n'));
console.log(`families=${families.length} formulas=${FORMULAS.length} companions=${COMPANIONS.length}`);
console.log(`L4 family tokens=${n4}  L3 family tokens=${n3}  (each = ${families.length}*2*9*${FORMULAS.length})`);
console.log(`wrote adapt-ab-theme/layers/L4-accent-spectrum.css and L3-accent-spectrum.css`);
