#!/usr/bin/env python3
"""render-pathway-benchmarks-md.py - the 9 pathway capabilities + benchmark keys, as Markdown.

For each academic-practice pathway: its 9 capabilities (3 per tier, the
definitive generics) and, per tier, the benchmark statements that key in
(benchmarkKeys.byTier, written by tools/key-benchmark-tiers.py). Keys decided
by capability-match are listed under their tier; progression / floor keys
apply at every tier, so they are listed once per pathway.

Each capability is marked by attribution (benchmarkKeys.attribution): direct,
indirect-only, or UNATTRIBUTED (no benchmark matched it). The 18 per pathway
are the evidence examples in catalogue/context/pathway-evidence/<pathway>.json:
two per capability, one conceptual and one applied (checked by
tools/check-pathway-evidence.py).

Run from the repo root:
    python tools/render-pathway-benchmarks-md.py
"""
import glob, json, os, re, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import pathway_tiers

REPO_ROOT = pathway_tiers.REPO_ROOT
OUT = os.path.join(REPO_ROOT, 'gate-experiment', 'pathway-capabilities-and-benchmark-keys.md')
UNIVERSAL = os.path.join(REPO_ROOT, 'catalogue', 'context', 'subject', 'benchmarks', 'universal-reference.json')
TIERS = pathway_tiers.TIERS
ORDER = json.load(open(os.path.join(REPO_ROOT, 'design-kb', 'design-kb.pathways.json'), encoding='utf-8'))['pathways']
EVIDENCE_DIR = os.path.join(REPO_ROOT, 'catalogue', 'context', 'pathway-evidence')
MARK = {'direct': 'direct', 'indirect-only': 'indirect only', 'unattributed': '**UNATTRIBUTED**'}


def evidence_for(pid):
    path = os.path.join(EVIDENCE_DIR, pid + '.json')
    if not os.path.exists(path):
        return {}
    return {c['capability']: c for c in json.load(open(path, encoding='utf-8')).get('capabilities') or []}


def md(s):
    s = re.sub(r'\s*—\s*', ', ', str(s or ''))
    return s.replace('|', '/').replace('\n', ' ').strip()


def title_of(doc, pid):
    t = (doc.get('identity') or {}).get('title') or pid
    return re.sub(r'\s*\(academic skills pathway\)\s*$', '', t, flags=re.I)


def label_for(key, comps):
    if key['source'] == 'universal-reference':
        c = comps.get(key['statementId'].split('/')[-1])
        return 'Universal: ' + (c['label'] if c else key['statementId'])
    return '%s %s: %s' % (key['source'].split('-')[0].title(), key['statementId'].split('/')[-1], md(key['extract']))


def render():
    u = json.load(open(UNIVERSAL, encoding='utf-8'))
    comps = {i['id']: i for i in u['graduate_competency']['items']}
    L = ['# Pathway capabilities: the 9, the 18 and benchmark keys by tier', '',
         'Generated by `tools/render-pathway-benchmarks-md.py`; do not hand-edit. Re-run after '
         '`tools/key-benchmark-tiers.py` or after editing `catalogue/context/pathway-evidence/`.', '',
         '- **The 9:** each pathway\'s capabilities, 3 per tier (`catalogue/context/pathway/<pathway>.json`).',
         '- **The 18:** two evidence examples per capability, one **conceptual** (theory, concept or model) and '
         'one **applied** (practice, real world): 6 per tier (`catalogue/context/pathway-evidence/<pathway>.json`). '
         'Draft for review.',
         '- **Attribution:** whether a benchmark lands on the capability. **direct** = a direct benchmark '
         'matched it; **indirect only**; **UNATTRIBUTED** = no benchmark matched it (every-tier keys do not count).',
         '- **Benchmark keys:** universal graduate competencies and subject statements (Psychology, the one '
         'authored subject map, keyed as a draft) that key into the pathway at each tier.', '',
         'Tier basis: **match** = matched a capability at that tier; **every tier** = progression (direct, no '
         'match) or floor (indirect, no match: weakest, review these).', '']
    unattr = []
    for p in ORDER:
        doc = json.load(open(os.path.join(pathway_tiers.PATHWAY_DIR, p['id'] + '.json'), encoding='utf-8'))
        attr = (doc.get('benchmarkKeys') or {}).get('attribution') or {}
        for c in doc.get('capabilities') or []:
            ref = c.get('capabilityId') or p['id'] + '#' + str(c.get('rowId'))
            if attr.get(ref) in ('unattributed', 'indirect-only'):
                unattr.append((title_of(doc, p['id']), c.get('tier'), md(c.get('statement')), MARK[attr[ref]], ref))
    L += ['## Capabilities without a direct benchmark (%d)' % len(unattr), '',
          '| Pathway | Tier | Capability | Attribution | Id |', '|---|---|---|---|---|']
    L += ['| %s | %s | %s | %s | `%s` |' % u for u in unattr] + ['']
    L += ['## Contents', ''] + ['%d. [%s](#%s)' % (i + 1, p['name'].strip(), p['id']) for i, p in enumerate(ORDER)] + ['']

    for p in ORDER:
        pid = p['id']
        doc = json.load(open(os.path.join(pathway_tiers.PATHWAY_DIR, pid + '.json'), encoding='utf-8'))
        caps = doc.get('capabilities') or []
        by = (doc.get('benchmarkKeys') or {}).get('byTier') or {}
        attr = (doc.get('benchmarkKeys') or {}).get('attribution') or {}
        ev = evidence_for(pid)
        L += ['<a id="%s"></a>' % pid, '## %s' % title_of(doc, pid), '']
        n = 0
        for t in TIERS:
            L += ['### %s' % t.title(), '', '| # | Capability | FHEQ | Framework anchor | Benchmark | Id |',
                  '|---|---|---|---|---|---|']
            tier_caps = [c for c in caps if c.get('tier') == t]
            first = n + 1
            matched = [k for k in by.get(t, []) if k['tierBasis'] == 'capability-match']
            for c in tier_caps:
                n += 1
                ref = c.get('capabilityId') or pid + '#' + str(c.get('rowId'))
                qf = '; '.join('%s "%s"' % (q.get('id'), md(q.get('extract'))) for q in c.get('qf') or [])
                L.append('| %d | %s | L%s | %s | %s | `%s` |' % (n, md(c.get('statement')), c.get('fheqLevel'), qf,
                                                                 MARK.get(attr.get(ref), '?'), ref))
            if ev:
                L += ['', '**Benchmark, generic learning outcomes and evidence, per capability:**', '']
                for i, c in enumerate(tier_caps):
                    ref = c.get('capabilityId') or pid + '#' + str(c.get('rowId'))
                    item = ev.get(ref)
                    L.append('%d. **%s**' % (first + i, md(c.get('statement'))))
                    landed = [k for k in matched if ref in (k.get('capabilities') or [])]
                    if landed:
                        for k in landed:
                            L.append('    - *Benchmark:* %s (%s)' % (label_for(k, comps), k['strength']))
                    else:
                        L.append('    - *Benchmark:* none matched at this tier (%s)' % MARK.get(attr.get(ref), '?'))
                    if not item:
                        L.append('    - *(no evidence examples yet)*'); continue
                    gos = item.get('genericOutcomes') or []
                    from_bm = [g for g in gos if g.get('origin') == 'from-benchmark']
                    if from_bm:
                        L.append('    - **Generic outcomes from the benchmark:**')
                        for g in sorted(from_bm, key=lambda g: g.get('kind') != 'conceptual'):
                            L.append('        - *%s: %s.* **Learning outcome:** %s' % (
                                g['kind'].title(), md(g.get('title')).rstrip('.'), md(g.get('learningOutcome'))))
                            L.append('          %s **Evidence:** %s *(Grounding: %s)*' % (
                                md(g.get('example')),
                                md(g.get('artefact')), '; '.join(md(x) for x in g.get('grounding') or [])))
                    L.append('    - **The existing practical examples (evidence a student could offer):**')
                    for e in sorted(item.get('evidence') or [], key=lambda e: e.get('kind') != 'conceptual'):
                        L.append('        - *%s: %s.* %s **Evidence:** %s *(Grounding: %s)*' % (
                            e['kind'].title(), md(e.get('title')).rstrip('.'), md(e.get('example')),
                            md(e.get('artefact')), '; '.join(md(x) for x in e.get('grounding') or [])))
            L += ['', '**Benchmarks keying in at this tier (match):**', '']
            if matched:
                for k in matched:
                    L.append('- %s (%s; lands on %s)' % (label_for(k, comps), k['strength'],
                                                        ', '.join('`%s`' % r for r in k['capabilities'])))
            else:
                L.append('- none matched; see the every-tier keys below')
            L.append('')
        every, seen = [], set()
        for t in TIERS:
            for k in by.get(t, []):
                if k['tierBasis'] != 'capability-match' and (k['source'], k['statementId']) not in seen:
                    seen.add((k['source'], k['statementId']))
                    every.append(k)
        L += ['### Keys at every tier', '']
        for basis in ('progression', 'floor'):
            ks = [k for k in every if k['tierBasis'] == basis]
            if ks:
                L += ['**%s:**' % basis.title(), ''] + ['- %s (%s)' % (label_for(k, comps), k['strength']) for k in ks] + ['']
        if not every:
            L += ['- none', '']
    return '\n'.join(L)


if __name__ == '__main__':
    with open(OUT, 'w', encoding='utf-8') as fh:
        fh.write(render())
    print('wrote', os.path.relpath(OUT, REPO_ROOT))
