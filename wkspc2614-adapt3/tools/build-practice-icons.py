#!/usr/bin/env python3
"""build-practice-icons.py - the academic practice icon sprite for courses.

One <symbol> per academic practice pathway, id `ap-<pathway id>`, taken from
the studio icon set (../abbott/assets/icons/ic-*.svg: Material Symbols
Outlined, weight 400, viewBox 0 -960 960 960, fill currentColor). Pathway order
and ids come from design-kb/design-kb.pathways.json; labels from the catalogue
pathway titles (with the old "(academic skills pathway)" suffix dropped).

Outputs, in the grow-ct theme (copied to build/assets/icons/ by grunt):
    src/theme/grow-ct/assets/icons/academic-practice.sprite.svg
    src/theme/grow-ct/assets/icons/academic-practice-icons.json   (pathway -> symbol, label, source)

Use in a page (inherits currentColor; give it its own accessible name):
    <svg class="ap-icon" role="img" aria-label="Criticality"><use href="assets/icons/academic-practice.sprite.svg#ap-criticality"/></svg>

Run from the repo root:
    python tools/build-practice-icons.py
"""
import json, os, re, sys

REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
STUDIO = os.path.join(os.path.dirname(REPO_ROOT), 'abbott', 'assets', 'icons')
OUT_DIR = os.path.join(REPO_ROOT, 'src', 'theme', 'grow-ct', 'assets', 'icons')
PATHWAYS = os.path.join(REPO_ROOT, 'design-kb', 'design-kb.pathways.json')
CATALOGUE = os.path.join(REPO_ROOT, 'catalogue', 'context', 'pathway')

# pathway id -> studio icon (abbott/assets/icons/<icon>.svg)
ICON_FOR = {
    'starting-progressing-succeeding': 'ic-starting',
    'understanding-learning-assessment-feedback': 'ic-assessment',
    'finding-using-sources': 'ic-finding',
    'referencing': 'ic-referencing',
    'criticality': 'ic-criticality',
    'academic-writing': 'ic-writing',
    'presenting': 'ic-presenting',
    'revising-exams': 'ic-revising-exams',
    'researching-research-methods': 'ic-researching',
    'reflective-practice': 'ic-reflecting',
    'work-based-experiential-learning': 'ic-work-based',
    'ai-technology': 'ic-ai-technology',
    'creativity': 'ic-creativity',
}


def label_for(pid, fallback):
    path = os.path.join(CATALOGUE, pid + '.json')
    title = fallback
    if os.path.exists(path):
        title = (json.load(open(path, encoding='utf-8')).get('identity') or {}).get('title') or fallback
    return re.sub(r'\s*\(academic skills pathway\)\s*$', '', title, flags=re.I).strip()


def read_icon(name):
    svg = open(os.path.join(STUDIO, name + '.svg'), encoding='utf-8').read()
    vb = re.search(r'viewBox="([^"]+)"', svg)
    body = re.search(r'<svg[^>]*>(.*)</svg>', svg, re.S)
    if not vb or not body:
        raise SystemExit('cannot read ' + name)
    return vb.group(1), body.group(1).strip()


def main():
    order = json.load(open(PATHWAYS, encoding='utf-8'))['pathways']
    missing = [p['id'] for p in order if p['id'] not in ICON_FOR]
    if missing:
        raise SystemExit('no icon mapped for: ' + ', '.join(missing))
    symbols, index = [], []
    for p in order:
        pid, icon = p['id'], ICON_FOR[p['id']]
        view_box, body = read_icon(icon)
        symbols.append('<symbol id="ap-%s" viewBox="%s" fill="currentColor">%s</symbol>' % (pid, view_box, body))
        index.append({'pathway': pid, 'symbol': 'ap-' + pid, 'label': label_for(pid, p.get('name', pid).strip()),
                      'source': 'abbott/assets/icons/%s.svg' % icon})
    os.makedirs(OUT_DIR, exist_ok=True)
    sprite = ('<svg xmlns="http://www.w3.org/2000/svg" aria-hidden="true" style="display:none">\n'
              '<!-- GENERATED by tools/build-practice-icons.py: academic practice pathway icons '
              '(Material Symbols Outlined, from abbott/assets/icons). Do not hand-edit. -->\n'
              + '\n'.join(symbols) + '\n</svg>\n')
    with open(os.path.join(OUT_DIR, 'academic-practice.sprite.svg'), 'w', encoding='utf-8', newline='\n') as fh:
        fh.write(sprite)
    with open(os.path.join(OUT_DIR, 'academic-practice-icons.json'), 'w', encoding='utf-8', newline='\n') as fh:
        fh.write(json.dumps({
            '_comment': 'GENERATED by tools/build-practice-icons.py. Pathway -> sprite symbol in '
                        'academic-practice.sprite.svg (served at assets/icons/).',
            'sprite': 'assets/icons/academic-practice.sprite.svg',
            'icons': index,
        }, ensure_ascii=False, indent=2) + '\n')
    print('wrote %d symbols to %s' % (len(symbols), os.path.relpath(OUT_DIR, REPO_ROOT)))


if __name__ == '__main__':
    main()
