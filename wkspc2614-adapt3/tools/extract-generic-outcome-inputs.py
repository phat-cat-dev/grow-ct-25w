#!/usr/bin/env python3
"""extract-generic-outcome-inputs.py - input packets for authoring generic
learning outcomes (the 9 -> 18 -> +4 layer).

For each pathway, emits one input packet to
/tmp/generic-outcome-inputs/<pathway>.json (not into the repo) so authoring
the 4 genericOutcomes entries per capability is reproducible and reviewable.

Per capability the packet carries:
  - capability ref, tier, statement, knowledgeKind
  - competency.theory[] ids plus their citations, resolved from
    catalogue/context/pathway-evidence/_theory-refs.json
  - competency.professional[] statements and frameworks[]
  - attribution (benchmarkKeys.attribution)
  - benchmarks[]: every benchmarkKeys.byTier entry naming this capability in
    its capabilities[] array, each with statementId, strength, tierBasis,
    extract
  - the existing evidence[] verbatim, from
    catalogue/context/pathway-evidence/<pathway>.json (the distillation source)

Run from the repo root:
    python tools/extract-generic-outcome-inputs.py              # all pathways
    python tools/extract-generic-outcome-inputs.py criticality  # one or more
"""
import glob, json, os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import pathway_tiers

REPO_ROOT = pathway_tiers.REPO_ROOT
PATHWAY_DIR = pathway_tiers.PATHWAY_DIR
EVIDENCE_DIR = os.path.join(REPO_ROOT, 'catalogue', 'context', 'pathway-evidence')
THEORY_REFS_PATH = os.path.join(EVIDENCE_DIR, '_theory-refs.json')
OUT_DIR = '/tmp/generic-outcome-inputs'


def load_theory_refs():
    doc = json.load(open(THEORY_REFS_PATH, encoding='utf-8'))
    return doc.get('refs') or {}


def benchmarks_for(ref, by_tier):
    """Every byTier entry across all tiers whose capabilities[] names ref."""
    out = []
    for tier in pathway_tiers.TIERS:
        for e in by_tier.get(tier, []):
            if ref in (e.get('capabilities') or []):
                out.append({
                    'statementId': e.get('statementId'),
                    'strength': e.get('strength'),
                    'tierBasis': e.get('tierBasis'),
                    'extract': e.get('extract'),
                })
    return out


def extract(pid, theory_refs):
    cap_doc = json.load(open(os.path.join(PATHWAY_DIR, pid + '.json'), encoding='utf-8'))
    ev_path = os.path.join(EVIDENCE_DIR, pid + '.json')
    ev_doc = json.load(open(ev_path, encoding='utf-8')) if os.path.exists(ev_path) else {}
    ev_by_ref = {c['capability']: c for c in ev_doc.get('capabilities') or []}
    bk = cap_doc.get('benchmarkKeys') or {}
    attribution = bk.get('attribution') or {}
    by_tier = bk.get('byTier') or {}

    packets = []
    for c in cap_doc.get('capabilities') or []:
        ref = c.get('capabilityId') or pid + '#' + str(c.get('rowId'))
        comp = c.get('competency') or {}
        theory_ids = [t for t in (comp.get('theory') or []) if isinstance(t, str)]
        theory = [{'id': t, 'citation': theory_refs.get(t, 'UNKNOWN')} for t in theory_ids]
        professional = []
        for p in comp.get('professional') or []:
            professional.append({
                'statement': p.get('statement'),
                'frameworks': p.get('frameworks') or [],
            })
        ev_item = ev_by_ref.get(ref) or {}
        packets.append({
            'capability': ref,
            'tier': c.get('tier'),
            'statement': c.get('statement'),
            'knowledgeKind': c.get('knowledgeKind'),
            'academicStatement': comp.get('academicStatement'),
            'competency': {
                'theory': theory,
                'professional': professional,
            },
            'attribution': attribution.get(ref),
            'benchmarks': benchmarks_for(ref, by_tier),
            'evidence': ev_item.get('evidence') or [],
        })
    return {
        'pathway': pid,
        'note': 'Input packet for authoring genericOutcomes (distilled + from-benchmark, '
                'conceptual + applied). Generated by tools/extract-generic-outcome-inputs.py.',
        'capabilities': packets,
    }


if __name__ == '__main__':
    pids = sys.argv[1:] or sorted(os.path.splitext(os.path.basename(p))[0]
                                  for p in glob.glob(os.path.join(EVIDENCE_DIR, '*.json'))
                                  if not os.path.basename(p).startswith('_'))
    os.makedirs(OUT_DIR, exist_ok=True)
    theory_refs = load_theory_refs()
    for pid in pids:
        packet = extract(pid, theory_refs)
        out_path = os.path.join(OUT_DIR, pid + '.json')
        with open(out_path, 'w', encoding='utf-8') as fh:
            json.dump(packet, fh, indent=2, ensure_ascii=False)
            fh.write('\n')
        print('wrote %s (%d capabilities)' % (out_path, len(packet['capabilities'])))
