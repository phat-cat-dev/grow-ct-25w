#!/usr/bin/env python3
"""key-benchmark-tiers.py - key benchmarks into pathways at pathway + tier.

Two passes, both using the shared rule in tools/pathway_tiers.py:

  1. Subject tiering. Every subject benchmark whose pathwayMapping is populated
     (today: psychology-2023 only; the other 53 are filled on demand) gains
     `tiers` + `tierBasis` on each mapped statement, matched by content-word
     overlap between the statement extract and the pathway's capabilities.
     The universal reference is tiered by its own builder
     (tools/build-universal-benchmark.py), not here.

  2. Reverse index. Each catalogue/context/pathway/<pathway>.json gains
     `benchmarkKeys.byTier`: every universal + tiered subject statement that
     keys into it, per tier, with the capabilities it lands on.

Re-run after build-universal-benchmark.py, after a subject map is authored, or
after build-pathway-reference.py regenerates the pathway files.

Run from the repo root:
    python tools/key-benchmark-tiers.py            # write both passes
    python tools/key-benchmark-tiers.py --check    # report only, write nothing
"""
import argparse, collections, glob, json, os
import pathway_tiers

REPO_ROOT = pathway_tiers.REPO_ROOT
BENCH_DIR = os.path.join(REPO_ROOT, 'catalogue', 'context', 'subject', 'benchmarks')
UNIVERSAL = 'universal-reference'


def load(path):
    return json.load(open(path, encoding='utf-8'))


def save(path, doc):
    with open(path, 'w', encoding='utf-8') as fh:
        json.dump(doc, fh, ensure_ascii=False, indent=2)
        fh.write('\n')


def tier_subject(doc):
    """Add tiers/tierBasis to each mapped statement; return the count tiered."""
    n = 0
    for pk, pw in (doc.get('pathwayMapping') or {}).items():
        for st in pw.get('statements') or []:
            text = ' '.join([str(st.get('extract') or ''), str(st.get('orientationExtract') or '')])
            st['tiers'], st['tierBasis'] = pathway_tiers.key_tiers(
                pk, st.get('strength'), text=text)
            n += 1
    return n


def collect(sources):
    """pathway key -> tier -> [key entries], from every keyed benchmark."""
    index = collections.defaultdict(lambda: collections.defaultdict(list))
    for name, doc in sources:
        for pk, pw in (doc.get('pathwayMapping') or {}).items():
            for st in pw.get('statements') or []:
                for t in st.get('tiers') or []:
                    index[pk][t['tier']].append({
                        'source': name,
                        'statementId': st.get('chunkId'),
                        'strength': st.get('strength'),
                        'tierBasis': st.get('tierBasis'),
                        'capabilities': t.get('capabilities') or [],
                        'extract': st.get('extract') or '',
                    })
    return index


def write_index(index, names, check):
    for path in sorted(glob.glob(os.path.join(pathway_tiers.PATHWAY_DIR, '*.json'))):
        pid = os.path.splitext(os.path.basename(path))[0]
        by = index.get('adapt-' + pid, {})
        keys = {
            'note': 'Benchmark statements keying into this pathway, by tier. Generated by '
                    'tools/key-benchmark-tiers.py; tierBasis says how the tier was decided '
                    '(capability-match | progression | floor). Do not hand-edit.',
            'sources': names,
            'byTier': {t: by.get(t, []) for t in pathway_tiers.TIERS},
        }
        print('  %-48s %s' % (pid, '  '.join('%s=%d' % (t[:5], len(keys['byTier'][t]))
                                               for t in pathway_tiers.TIERS)))
        if check:
            continue
        doc = load(path)
        doc.pop('benchmarkKeys', None)
        out = {}
        for k, v in doc.items():
            out[k] = v
            if k == 'capabilities':
                out['benchmarkKeys'] = keys
        if 'benchmarkKeys' not in out:
            out['benchmarkKeys'] = keys
        save(path, out)


if __name__ == '__main__':
    ap = argparse.ArgumentParser(description='Key benchmarks into pathways at pathway + tier.')
    ap.add_argument('--check', action='store_true', help='report only, write nothing')
    args = ap.parse_args()

    sources = []
    for path in sorted(glob.glob(os.path.join(BENCH_DIR, '*.json'))):
        doc = load(path)
        name = doc.get('subjectBenchmarkId') or os.path.splitext(os.path.basename(path))[0]
        if not doc.get('pathwayMapping'):
            continue
        if name != UNIVERSAL:
            n = tier_subject(doc)
            print('tiered %-30s %d statements' % (name, n))
            if not args.check:
                save(path, doc)
        sources.append((name, doc))

    print('reverse index (%s):' % ', '.join(n for n, _ in sources))
    write_index(collect(sources), [n for n, _ in sources], args.check)
