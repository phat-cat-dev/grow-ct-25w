#!/usr/bin/env node
'use strict';

// render-map-md.js <map.json>
//
// Renders a benchmark-to-pathway map (source-mapping-rules.md section 6
// shape) as a Markdown file, written beside the map with the same base name
// and a ".md" extension in place of ".json". Node.js, no dependencies.
//
// One section per pathway, in catalogue/context/pathways.json order. A pathway with
// no statements is listed as having none. The whole-map agentInstructions
// are rendered once, at the top. The file's own first line states that it
// is generated and must never be hand-edited.

const fs = require('fs');
const path = require('path');

const REPO_ROOT = path.resolve(__dirname, '..', '..', '..', '..');
const CATALOGUE_PATH = path.join(REPO_ROOT, 'catalogue', 'context', 'pathways.json');

function readJSON(absPath) {
  const raw = fs.readFileSync(absPath, 'utf8');
  return JSON.parse(raw);
}

function loadCatalogue() {
  const catalogue = readJSON(CATALOGUE_PATH);
  return catalogue.pathways;
}

function mdEscapePipes(s) {
  return String(s).replace(/\|/g, '\\|').replace(/\n/g, ' ');
}

function renderCoverageLine(tag, coverageValue) {
  if (coverageValue === 'none' || coverageValue === undefined) {
    return `**Coverage:** none`;
  }
  const direct = coverageValue.direct;
  const indirect = coverageValue.indirect;
  return `**Coverage:** direct ${direct}, indirect ${indirect}`;
}

function renderStatementsTable(statements) {
  const header = '| chunk id | strength | block type | orientation | extract | agent instruction | status |';
  const rule = '|---|---|---|---|---|---|---|';
  const order = { direct: 0, indirect: 1 };
  const sorted = statements.slice().sort((a, b) => {
    const ao = order[a.strength] !== undefined ? order[a.strength] : 2;
    const bo = order[b.strength] !== undefined ? order[b.strength] : 2;
    return ao - bo;
  });
  const rows = sorted.map((st) => {
    return `| ${mdEscapePipes(st.chunkId)} | ${mdEscapePipes(st.strength)} | ${mdEscapePipes(st.blockType)} | ${mdEscapePipes(st.orientation)} | ${mdEscapePipes(st.extract)} | ${mdEscapePipes(st.agentInstruction)} | ${mdEscapePipes(st.status)} |`;
  });
  return [header, rule, ...rows].join('\n');
}

function renderPathwaySection(pathwayId, tag, map) {
  const group = map.pathways && map.pathways[tag];
  const coverageValue = map.coverage && map.coverage[tag];
  const lines = [];
  lines.push(`## ${tag}`);
  lines.push('');
  lines.push(renderCoverageLine(tag, coverageValue));
  lines.push('');
  if (!group || !Array.isArray(group.statements) || group.statements.length === 0) {
    lines.push('No statements for this pathway.');
    return lines.join('\n');
  }
  if (group.summary && typeof group.summary.text === 'string') {
    lines.push(`**Summary (${group.summary.status}):** ${group.summary.text}`);
    if (Array.isArray(group.summary.basis) && group.summary.basis.length > 0) {
      lines.push('');
      lines.push(`**Basis:** ${group.summary.basis.map(mdEscapePipes).join(', ')}`);
    }
    lines.push('');
  }
  lines.push(renderStatementsTable(group.statements));
  return lines.join('\n');
}

function renderMarkdown(map, mapArgRelPath) {
  const catalogue = loadCatalogue();
  const lines = [];
  lines.push(`<!-- Generated by render-map-md.js from "${mapArgRelPath}". Do not hand-edit; edit the map and regenerate. -->`);
  lines.push('');
  lines.push(`# ${map.source && map.source.title ? map.source.title : map.source && map.source.id}: benchmark map`);
  lines.push('');
  lines.push(`Source: \`${map.source && map.source.id}\` · Rules: \`${map.rules}\` · Map version: \`${map.mapVersion}\``);
  lines.push('');
  if (Array.isArray(map.agentInstructions) && map.agentInstructions.length > 0) {
    lines.push('## Agent instructions (whole map)');
    lines.push('');
    for (const instr of map.agentInstructions) {
      lines.push(`- ${instr}`);
    }
    lines.push('');
  }
  for (const pathway of catalogue) {
    const tag = `adapt-${pathway.id}`;
    lines.push(renderPathwaySection(pathway.id, tag, map));
    lines.push('');
  }
  if (Array.isArray(map.excluded) && map.excluded.length > 0) {
    lines.push('## Excluded chunks');
    lines.push('');
    lines.push('| chunk id | reason |');
    lines.push('|---|---|');
    for (const ex of map.excluded) {
      lines.push(`| ${mdEscapePipes(ex.chunkId)} | ${mdEscapePipes(ex.reason)} |`);
    }
    lines.push('');
  }
  return lines.join('\n').replace(/\n{3,}/g, '\n\n').trimEnd() + '\n';
}

function outputPathFor(mapPath) {
  const dir = path.dirname(mapPath);
  const base = path.basename(mapPath);
  const mdBase = base.endsWith('.json') ? base.slice(0, -'.json'.length) + '.md' : base + '.md';
  return path.join(dir, mdBase);
}

function main() {
  const mapArg = process.argv[2];
  if (!mapArg) {
    console.error('Usage: render-map-md.js <map.json>');
    process.exit(2);
  }
  const mapPath = path.resolve(mapArg);
  let map;
  try {
    map = readJSON(mapPath);
  } catch (e) {
    console.error(`FATAL: cannot read or parse "${mapArg}": ${e.message}`);
    process.exit(1);
  }
  const md = renderMarkdown(map, mapArg);
  const outPath = outputPathFor(mapPath);
  fs.writeFileSync(outPath, md, 'utf8');
  console.log(`Wrote ${outPath}`);
  process.exit(0);
}

if (require.main === module) {
  main();
}

module.exports = {
  renderMarkdown,
  outputPathFor,
  loadCatalogue,
  REPO_ROOT,
};
